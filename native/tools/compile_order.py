#!/usr/bin/env python3
"""Write GameOrder.props: the game's files in the order of the JS they port.

A browser runs the script top to bottom, so a constant is always set up before
anything below it reads it. C# runs a partial class's static field initialisers
file by file, in the order the compiler is handed the files. Handing it the game's
files in JS order (each file's header names the JS line it starts at) keeps every
initialiser after the ones it reads, as in the browser.

Run:  python3 native/tools/compile_order.py   (after adding or renaming a file in src/Game)
"""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
gdir = os.path.join(root, 'src', 'Game')
rows = []
for f in sorted(os.listdir(gdir)):
    if not f.endswith('.cs'): continue
    head = open(os.path.join(gdir, f), encoding='utf-8').read(3000)
    m = re.search(r'(?:JS|lines)\s+(\d+)', head)
    rows.append((int(m.group(1)) if m else 0, f))
rows.sort()
out = ['<Project>', '  <!-- generated by tools/compile_order.py: the game files in the order of the JS they port -->', '  <ItemGroup>']
out += [f'    <GameOrdered Include="src/Game/{f}" />  <!-- JS {n} -->' for n, f in rows]
out += ['  </ItemGroup>', '</Project>', '']
open(os.path.join(root, 'GameOrder.props'), 'w').write('\n'.join(out))
print(f'{len(rows)} files')
